  outcomes: string[];
  audience: string[];
  marketGrowth: MarketGrowth;
  careers: CareerOpportunity[];
  keyAspects: KeyAspect[];
  modules: CourseModule[];
  certifications: CourseCertification[];
  learnerStories: LearnerStory[];
