export interface CourseModule {
  title: string;
  description: string;
}

export interface CourseCertification {
  title: string;
  description: string;
}

export interface LearnerStory {
  name: string;
  country: string;
  rating: number;
  review: string;
}

export interface CourseFaq {
  question: string;
  answer: string;
}

export interface CareerOpportunity {
  role: string;
  salary: string;
  companies: string[];
}

