  categorySlug: string;       // URL name e.g. "programming"
  originalPrice?: string;     // Strikethrough price e.g. "$199"
  discountPercent?: number;   // e.g. 55
  reviewCount?: number;       
  requirements?: string;      // Stats bar requirement text
  certificate?: string;       // Stats bar certificate text
